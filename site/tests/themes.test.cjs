const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const T=require('../src/sacra-themes.js');
const registry=JSON.parse(fs.readFileSync(path.join(__dirname,'..','themes.json'),'utf8'));
assert.equal(T.all.length,8);
assert.equal(registry.themes.length,8);
assert.deepEqual(registry.themes.map(x=>x.id),T.all.map(x=>x.id));
assert.equal(T.default,'sacra');
const roles=Object.keys(T.all[0].colors).sort();
for(const theme of T.all)assert.deepEqual(Object.keys(theme.colors).sort(),roles,theme.id+' role set');
const writes=[];
const fake={style:{setProperty:(k,v)=>writes.push([k,v])},dataset:{}};
const solar=T.apply('solarized-light',{roots:fake,emit:false});
assert.equal(solar.scheme,'light');
assert.equal(fake.dataset.sacraTheme,'solarized-light');
assert.equal(writes.length,roles.length);
assert.ok(writes.every(([k])=>k.startsWith('--s-color-')));
assert.equal(T.get('does-not-exist').id,'sacra');
console.log('SACRA web themes: OK · 8 palettes · '+roles.length+' semantic roles');
